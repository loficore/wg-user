#!/system/bin/sh
# wg-user uninstall hook (KernelSU / Magisk).
#
# KernelSU runs this via:
#   busybox sh /data/adb/modules/<id>/uninstall.sh
# with CWD set to the script's parent (the module root). Magisk behaves
# similarly. So $0 is the absolute script path and CWD is the module root;
# either source is reliable.
set -e

trace() { printf 'wg-user uninstall: %s\n' "$*" >&2; }

MODDIR=""
case "$0" in
    /*)
        cand="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
        [ -f "$cand/module.prop" ] && MODDIR="$cand"
        ;;
esac
if [ -z "$MODDIR" ]; then
    for cand in "${MODPATH:-}" "${MODDIR:-}" "$(pwd)"; do
        [ -n "$cand" ] || continue
        if [ -f "$cand/module.prop" ]; then MODDIR="$cand"; break; fi
    done
fi

# Drop a trailing slash so "$MODDIR/wg-user-reload" matches the path that
# watcher_is_ours reads out of /proc/<pid>/cmdline.
while [ -n "${MODDIR%/}" ] && [ "${MODDIR%/}" != "$MODDIR" ]; do
    MODDIR="${MODDIR%/}"
done

trace "module root: ${MODDIR:-<not found>}"

# watcher_is_ours <pid> — 0 when /proc/<pid>/cmdline is this module's reload
# watcher. Same shape as wg-user's pid_is_wguser: the pidfile outlives crashes
# and, after an unclean reboot, may name an unrelated root process, so only
# argv[0]/argv[1] are compared (a stranger carrying the path as a later
# argument is not adopted) and an unreadable cmdline fails closed.
watcher_is_ours() {
    [ -r "/proc/$1/cmdline" ] || return 1
    _argv0=$(tr '\0' '\n' < "/proc/$1/cmdline" 2>/dev/null | sed -n '1p')
    _argv1=$(tr '\0' '\n' < "/proc/$1/cmdline" 2>/dev/null | sed -n '2p')
    [ "$_argv0" = "$MODDIR/wg-user-reload" ] || [ "$_argv1" = "$MODDIR/wg-user-reload" ]
}

# Stop the reload watcher FIRST, before the daemon. The watcher ($MODDIR/
# wg-user-reload, generated by service.sh) polls every 5 s and on a config
# change calls `wg-user reload`, which starts the daemon again; stopping the
# daemon first would leave a window in which an uninstall brings it back up
# against a module directory that is about to be deleted. `wg-user stop` does
# not know about the watcher, so it cannot cover that window.
#
# The pidfile outlives crashes in /data/adb and, after an unclean reboot, may
# name an unrelated root process, so it is only signalled when it is alive and
# /proc/<pid>/cmdline (argv[0]/argv[1]) is our watcher script. A stale pid, a
# stranger and an unreadable cmdline are all left alone — and the pidfile is
# removed below regardless. Nothing here may fail the uninstall.
if [ -n "$MODDIR" ] && [ -f "$MODDIR/run/watcher.pid" ]; then
    _wpid=$(cat "$MODDIR/run/watcher.pid" 2>/dev/null) || _wpid=""
    if [ -n "$_wpid" ] && kill -0 "$_wpid" 2>/dev/null && watcher_is_ours "$_wpid"; then
        kill -TERM "$_wpid" 2>/dev/null || true
        trace "stopped the reload watcher (pid $_wpid)"
    fi
fi

# Stop the daemon through the CLI, not by killing its pidfile: the pidfile
# survives crashes in /data/adb and, after a reboot, may name an unrelated root
# process. The CLI validates /proc/<pid>/cmdline before it signals anything.
# The rm below is belt and braces for a stop that could not run at all.
if [ -n "$MODDIR" ] && [ -x "$MODDIR/wg-user" ]; then
    "$MODDIR/wg-user" stop 2>/dev/null || true
fi

rm -f "${MODDIR:-.}/run/wg-user.pid" "${MODDIR:-.}/run/watcher.pid" "${MODDIR:-.}/run/state"
exit 0
